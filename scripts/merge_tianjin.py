def parse_m3u(text):
    out = {}
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        ln = lines[i].strip()
        if ln.startswith("#EXTINF"):
            tvg_name = re.search(r'tvg-name="([^"]*)"', ln)
            logo = re.search(r'tvg-logo="([^"]*)"', ln)
            j = i + 1
            while j < len(lines) and lines[j].strip() == "":
                j += 1
            url = lines[j].strip() if j < len(lines) else ""
            m = re.search(r'/rtp/([\d.]+:\d+)', url)
            if m:
                name = ln.rsplit(",", 1)[-1].strip()
                out[m.group(1)] = (name, tvg_name.group(1) if tvg_name else "",
                                   logo.group(1) if logo else "", url)
            i = j + 1
        else:
            i += 1
    return out


def add_spaces(name):
    # 字母/数字标识与中文之间补空格（与 update_channels.py 一致）。幂等。
    name = re.sub(r'(CCTV-\d+\+?)(?=[\u4e00-\u9fff])', r'\1 ', name)
    name = re.sub(r'^(BRTV|CHC|IPTV|CGTN)(?=[\u4e00-\u9fff])', r'\1 ', name)
    name = re.sub(r'(?<=[\u4e00-\u9fff])(?=4K|HDR|SDR)', ' ', name)
    name = re.sub(r'(北京IPTV)(?=[\u4e00-\u9fff])', r'\1 ', name)
    return name


def main():
    bj_text = open(BJ, encoding="utf-8").read().rstrip("\n")
    bj_count = len(re.findall(r'^#EXTINF', bj_text, re.M))
    tj = parse_m3u(open(TJ, encoding="utf-8").read())

    order = [a for a in TJ_EXTRA if a in tj]
    missing = [a for a in TJ_EXTRA if a not in tj]
    if missing:
        print("!! 天津文件中找不到这些地址，请核对 TJ_EXTRA:\n  " + "\n  ".join(missing))
        raise SystemExit(1)

    block = []
    for a in order:
        tid, group = TJ_EXTRA[a]
        name, tvg_name, logo, url = tj[a]
        name = re.sub(r'\s+SD$', '', name)  # 去掉天津的标清后缀，与北京去清晰度标签一致
        name = add_spaces(name)
        block.append(f'#EXTINF:-1 tvg-id="{tid}" tvg-name="{tvg_name}" tvg-logo="{logo}" group-title="{group}",{name}')
        block.append(url)

    open(OUT, "w", encoding="utf-8").write(bj_text + "\n\n" + "\n".join(block) + "\n")
    print(f"已生成 {OUT}：北京 {bj_count} + 天津补充 {len(order)} = {bj_count + len(order)} 个频道")


if __name__ == "__main__":
    main()
